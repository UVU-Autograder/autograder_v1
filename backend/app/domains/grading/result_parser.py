"""Parser for structured pytest results produced by the runner script.

The runner script (generated by :mod:`runner_gen`) outputs a JSON blob to
stdout after running pytest inside the Judge0 sandbox.  This module parses
that JSON into strongly-typed dataclasses and provides score calculation
against the assignment's :class:`ScoringItemConfig` list.
"""

from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass, field

from app.domains.assignments.schemas import ScoringItemConfig, pytest_marker_for_key
from app.domains.grading.schemas import classify_execution_failure
from app.domains.grading.report_contract import RunnerPayload, ValidatedManifest, MAX_REPORT_BYTES
from pydantic import ValidationError
from app.core.audit_log import audit_event

logger = logging.getLogger(__name__)

# Maximum length of a failure message stored per test (keeps DB rows small).
MAX_MESSAGE_LENGTH = 2000


# ---------------------------------------------------------------------------
# Data structures
# ---------------------------------------------------------------------------


@dataclass
class PytestTestResult:
    """Result of a single pytest test function."""

    nodeid: str
    """Fully-qualified node id, e.g. ``assignment_tests.py::test_add_numbers_positive_values``."""

    outcome: str
    """One of ``"passed"``, ``"failed"``, ``"error"``, or ``"skipped"``."""

    markers: list[str]
    """List of ``ag_*`` marker names found on the test item."""

    duration: float
    """Wall-clock duration in seconds."""

    message: str | None
    """Short, sanitized failure/error message (``None`` when passed/skipped)."""

    actual: str | None = None
    expected: str | None = None
    expected_input: str | None = None
    failure_category: str | None = None
    output_truncated: bool = False


@dataclass
class PytestRunResult:
    """Aggregated result of a full pytest invocation."""

    tests: list[PytestTestResult] = field(default_factory=list)
    """Per-test results."""

    total: int = 0
    passed: int = 0
    failed: int = 0
    errors: int = 0
    duration: float = 0.0
    exit_code: int = -1

    collected: list[dict] = field(default_factory=list)
    diagnostics: dict = field(default_factory=dict)
    error_message: str | None = None
    """Set when pytest itself failed to run (bad import, syntax error, etc.)."""

    failure_category: str | None = None
    """Diagnostic failure category derived from exit codes and stderr/message patterns."""


# ---------------------------------------------------------------------------
# Parsing helpers
# ---------------------------------------------------------------------------


def _truncate(text: str | None, max_length: int = MAX_MESSAGE_LENGTH) -> str | None:
    """Truncate *text* to *max_length*, appending an ellipsis if trimmed."""
    if text is None:
        return None
    if len(text) <= max_length:
        return text
    return text[: max_length - 3] + "..."


def _unique_object(pairs: list[tuple[str, object]]) -> dict:
    result: dict = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("Duplicate JSON key")
        result[key] = value
    return result


def parse_pytest_json(
    raw_stdout: str, *, stderr: str = "", exit_code: int = -1,
    expected_manifest: dict | None = None,
) -> PytestRunResult:
    """Accept only a complete, bounded protocol-2 envelope; never scan console text."""
    try:
        if len(raw_stdout.encode("utf-8")) > MAX_REPORT_BYTES:
            raise ValueError("Report too large")
        data = json.loads(raw_stdout, object_pairs_hook=_unique_object,
                          parse_constant=lambda value: (_ for _ in ()).throw(ValueError("Non-finite JSON number")))
        payload = RunnerPayload.model_validate(data)
        if payload.infrastructure_error:
            audit_event("grading.infrastructure_error", failure_category="infrastructure_error", failure_count=1)
            return PytestRunResult(
                exit_code=payload.summary.exit_code or exit_code,
                error_message=payload.infrastructure_error,
                failure_category="infrastructure_error",
                diagnostics=payload.diagnostics.model_dump(),
            )
        if not payload.completed:
            raise ValueError("Runner did not complete")
        if not payload.collected:
            raise ValueError("No collected cases")
        if expected_manifest is not None:
            manifest = ValidatedManifest.model_validate(expected_manifest)
            expected = {case.nodeid: (sorted(case.markers), case.xfail) for case in manifest.cases}
            actual = {case.nodeid: (sorted(case.markers), case.xfail) for case in payload.collected}
            if expected != actual:
                audit_event("grading.inventory_mismatch", warning_count=len(set(expected) ^ set(actual)),
                            failure_category="invalid_runner_report")
                raise ValueError("Case inventory mismatch")
        tests = []
        for entry in payload.tests:
            category = entry.failure_category
            if not category and entry.outcome != "passed":
                classified = classify_execution_failure(message=entry.message, outcome=entry.outcome)
                category = classified.value if classified else None
            tests.append(PytestTestResult(nodeid=entry.nodeid, outcome=entry.outcome, markers=entry.markers,
                duration=entry.duration, message=entry.message, actual=entry.actual, expected=entry.expected,
                expected_input=entry.expected_input, failure_category=category, output_truncated=entry.output_truncated))
        summary = payload.summary
        return PytestRunResult(tests=tests, total=summary.total, passed=summary.passed, failed=summary.failed,
            errors=summary.errors, duration=summary.duration, exit_code=summary.exit_code,
            collected=[case.model_dump() for case in payload.collected], diagnostics=payload.diagnostics.model_dump(),
            failure_category=next((t.failure_category for t in tests if t.outcome != "passed"), None))
    except (ValueError, TypeError, ValidationError, RecursionError):
        audit_event("grading.report_rejected", failure_category="invalid_runner_report", failure_count=1)
        return PytestRunResult(exit_code=exit_code, error_message="Grading report is invalid or incomplete. Instructor review is required.",
                               failure_category="invalid_runner_report")


# ---------------------------------------------------------------------------
# Score calculation
# ---------------------------------------------------------------------------


def _clean_assertion_target(match: re.Match) -> tuple[str, str]:
    act_str = match.group(1).strip().strip("'\"")
    exp_str = match.group(3).strip().strip("'\"")
    msg_match = re.search(r"^(.+?),\s*([\"'].*[\"'])$", exp_str)
    if msg_match:
        exp_str = msg_match.group(1).strip().strip("'\"")
    return act_str, exp_str


def _extract_assertion_values(message: str | None, actual: str | None = None, expected: str | None = None) -> tuple[str | None, str | None]:
    """Extract your_value (actual) and expected_value (expected) from failure message or result attributes."""
    if actual is not None or expected is not None:
        return actual, expected

    if not message:
        return None, None

    # Priority 1: Pytest evaluated failure line (e.g. "E       assert -1.0 == 0.0")
    for line in message.splitlines():
        line_str = line.strip()
        if line_str.startswith("E ") and "assert " in line_str:
            match = re.search(r"E\s+assert\s+(.+?)\s*(==|in|>|<|!=)\s*(.+)$", line_str)
            if match:
                return _clean_assertion_target(match)

    # Priority 2: Standard assert statement line in traceback
    for line in message.splitlines():
        line_str = line.strip()
        if "AssertionError:" in line_str or "assert " in line_str:
            match = re.search(r"assert\s+(.+?)\s*(==|in|>|<|!=)\s*(.+)$", line_str)
            if match:
                return _clean_assertion_target(match)

            if "assert False" in line_str or "assert false" in line_str:
                return "false", "true"

    return None, None


def calculate_scores(
    run_result: PytestRunResult,
    test_configs: list[ScoringItemConfig],
) -> tuple[int, list[dict]]:
    """Calculate the score from pytest results mapped to config scoring items.

    For each :class:`ScoringItemConfig`:

    1. Derive the expected marker via :func:`pytest_marker_for_key`
       (``ag_<key>``).
    2. Find **all** :class:`PytestTestResult` entries whose *markers* list
       contains the expected marker.
    3. The item **passes** only if every matching pytest function has
       ``outcome == "passed"`` and at least one matching test was found.
    4. If the item passes, its *points* are added to the total score.

    Args:
        run_result: The parsed pytest run result.
        test_configs: The assignment's test item configuration list.

    Returns:
        A ``(total_score, details)`` tuple where *details* is a list of
        per-item result dicts.
    """
    if run_result.error_message:
        return 0, []
    # Build a lookup: marker -> list of PytestTestResult.
    marker_index: dict[str, list[PytestTestResult]] = {}
    for test in run_result.tests:
        for marker in test.markers:
            marker_index.setdefault(marker, []).append(test)

    total_score = 0
    details: list[dict] = []

    for config in test_configs:
        if config.item_type != "pytest":
            continue
        marker = pytest_marker_for_key(config.key)
        matching_tests = marker_index.get(marker, [])

        # Item passes only when ALL matching tests passed and at least one
        # matching test exists.
        passed = len(matching_tests) > 0 and all(
            t.outcome == "passed" for t in matching_tests
        )
        points_awarded = config.points if passed else 0
        total_score += points_awarded

        test_result_details = []
        for t in matching_tests:
            your_val, exp_val = _extract_assertion_values(t.message, t.actual, t.expected)
            cat = t.failure_category
            if not cat and t.outcome != "passed":
                classified = classify_execution_failure(message=t.message, outcome=t.outcome)
                cat = classified.value if classified is not None else None
            test_result_details.append(
                {
                    "nodeid": t.nodeid,
                    "outcome": t.outcome,
                    "duration": t.duration,
                    "message": t.message,
                    "actual": t.actual,
                    "expected": t.expected,
                    "your_value": your_val,
                    "expected_value": exp_val,
                    "expected_input": t.expected_input,
                    "failure_category": cat,
                    "output_truncated": t.output_truncated,
                }
            )

        item_your_val = None
        item_exp_val = None
        item_failure_cat = None
        if not passed:
            for tr in test_result_details:
                if item_failure_cat is None and tr.get("failure_category"):
                    item_failure_cat = tr.get("failure_category")
                if tr.get("your_value") is not None or tr.get("expected_value") is not None:
                    item_your_val = tr.get("your_value")
                    item_exp_val = tr.get("expected_value")
                    break

        details.append(
            {
                "key": config.key,
                "label": config.label,
                "points": config.points,
                "points_awarded": points_awarded,
                "passed": passed,
                "extra_credit": config.extra_credit,
                "item_type": config.item_type,
                "marker": marker,
                "your_value": item_your_val,
                "expected_value": item_exp_val,
                "failure_category": item_failure_cat,
                "hint": config.hint if not passed else None,
                "output_truncated": any(t.output_truncated for t in matching_tests),
                "test_results": test_result_details,
            }
        )

    return total_score, details


class PytestOutcomeParser:
    """Cohesive parser for Pytest execution outputs, assertion diffs, and score calculations."""

    @staticmethod
    def parse_execution_output(
        stdout: str,
        stderr: str = "",
        test_configs: list[ScoringItemConfig] | None = None,
        exit_code: int = -1,
    ) -> tuple[PytestRunResult, tuple[int, list[dict]]]:
        run_result = parse_pytest_json(stdout, stderr=stderr, exit_code=exit_code)
        if test_configs is None:
            return run_result, (0, [])
        score, details = calculate_scores(run_result, test_configs)
        return run_result, (score, details)

