"""Parser for structured pytest results produced by the runner script.

The runner script (generated by :mod:`runner_gen`) outputs a JSON blob to
stdout after running pytest inside the Judge0 sandbox.  This module parses
that JSON into strongly-typed dataclasses and provides score calculation
against the assignment's :class:`TestItemConfig` list.
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field

from app.domains.assignments.schemas import TestItemConfig, pytest_marker_for_key

logger = logging.getLogger(__name__)

# Delimiter emitted by the runner script right before the JSON payload.
RESULTS_DELIMITER = "---AUTOGRADER_RESULTS---"

# Maximum length of a failure message stored per test (keeps DB rows small).
MAX_MESSAGE_LENGTH = 2000


# ---------------------------------------------------------------------------
# Data structures
# ---------------------------------------------------------------------------


@dataclass
class PytestTestResult:
    """Result of a single pytest test function."""

    nodeid: str
    """Fully-qualified node id, e.g. ``assignment_tests.py::test_add_numbers_positive_values``."""

    outcome: str
    """One of ``"passed"``, ``"failed"``, ``"error"``, or ``"skipped"``."""

    markers: list[str]
    """List of ``ag_*`` marker names found on the test item."""

    duration: float
    """Wall-clock duration in seconds."""

    message: str | None
    """Short, sanitized failure/error message (``None`` when passed/skipped)."""

    actual: str | None = None
    expected: str | None = None


@dataclass
class PytestRunResult:
    """Aggregated result of a full pytest invocation."""

    tests: list[PytestTestResult] = field(default_factory=list)
    """Per-test results."""

    total: int = 0
    passed: int = 0
    failed: int = 0
    errors: int = 0
    duration: float = 0.0
    exit_code: int = -1

    error_message: str | None = None
    """Set when pytest itself failed to run (bad import, syntax error, etc.)."""


# ---------------------------------------------------------------------------
# Parsing helpers
# ---------------------------------------------------------------------------


def _truncate(text: str | None, max_length: int = MAX_MESSAGE_LENGTH) -> str | None:
    """Truncate *text* to *max_length*, appending an ellipsis if trimmed."""
    if text is None:
        return None
    if len(text) <= max_length:
        return text
    return text[: max_length - 3] + "..."


def _extract_json_string(raw_stdout: str) -> str | None:
    """Try to locate the JSON payload inside *raw_stdout*.

    Strategy (in priority order):
    1. Split on the ``RESULTS_DELIMITER`` and take the text after it.
    2. Scan lines in reverse for the first line starting with ``{``.
    3. Return ``None`` if nothing looks like JSON.
    """
    # Strategy 1: explicit delimiter.
    if RESULTS_DELIMITER in raw_stdout:
        _, _, after = raw_stdout.partition(RESULTS_DELIMITER)
        after = after.strip()
        if after:
            return after

    # Strategy 2: last JSON-like line.
    for line in reversed(raw_stdout.splitlines()):
        stripped = line.strip()
        if stripped.startswith("{"):
            return stripped

    return None


def _parse_test_entry(entry: dict) -> PytestTestResult:
    """Convert a single test dict from the JSON payload."""
    return PytestTestResult(
        nodeid=entry.get("nodeid", "<unknown>"),
        outcome=entry.get("outcome", "error"),
        markers=entry.get("markers", []),
        duration=float(entry.get("duration", 0.0)),
        message=_truncate(entry.get("message")),
        actual=entry.get("actual"),
        expected=entry.get("expected"),
    )


def parse_pytest_json(raw_stdout: str) -> PytestRunResult:
    """Parse the JSON output produced by the runner script.

    The runner outputs a JSON object with the following top-level keys:

    * ``tests`` – list of per-test dicts (``nodeid``, ``outcome``,
      ``markers``, ``duration``, ``message``).
    * ``summary`` – dict with ``total``, ``passed``, ``failed``, ``errors``,
      ``duration``, ``exit_code``.

    If *raw_stdout* does not contain valid JSON (e.g. the student's code
    printed garbage to stdout), the function attempts to extract the JSON
    after a known delimiter or from the last JSON-looking line.  If that also
    fails, it returns a :class:`PytestRunResult` with *error_message* set.

    Args:
        raw_stdout: The full stdout captured from the Judge0 execution.

    Returns:
        A populated :class:`PytestRunResult`.
    """
    json_str = _extract_json_string(raw_stdout)

    if json_str is None:
        return PytestRunResult(
            error_message="No JSON payload found in runner output.",
        )

    try:
        data = json.loads(json_str)
    except json.JSONDecodeError as exc:
        return PytestRunResult(
            error_message=f"Invalid JSON in runner output: {exc}",
        )

    if not isinstance(data, dict):
        return PytestRunResult(
            error_message=f"Expected a JSON object, got {type(data).__name__}.",
        )

    # Parse individual test entries.
    tests: list[PytestTestResult] = []
    for entry in data.get("tests", []):
        tests.append(_parse_test_entry(entry))

    # Parse the summary block.
    summary = data.get("summary", {})

    return PytestRunResult(
        tests=tests,
        total=int(summary.get("total", len(tests))),
        passed=int(summary.get("passed", 0)),
        failed=int(summary.get("failed", 0)),
        errors=int(summary.get("errors", 0)),
        duration=float(summary.get("duration", 0.0)),
        exit_code=int(summary.get("exit_code", -1)),
        error_message=None,
    )


# ---------------------------------------------------------------------------
# Score calculation
# ---------------------------------------------------------------------------


def calculate_scores(
    run_result: PytestRunResult,
    test_configs: list[TestItemConfig],
) -> tuple[int, list[dict]]:
    """Calculate the score from pytest results mapped to config scoring items.

    For each :class:`TestItemConfig`:

    1. Derive the expected marker via :func:`pytest_marker_for_key`
       (``ag_<key>``).
    2. Find **all** :class:`PytestTestResult` entries whose *markers* list
       contains the expected marker.
    3. The item **passes** only if every matching pytest function has
       ``outcome == "passed"`` and at least one matching test was found.
    4. If the item passes, its *points* are added to the total score.

    Args:
        run_result: The parsed pytest run result.
        test_configs: The assignment's test item configuration list.

    Returns:
        A ``(total_score, details)`` tuple where *details* is a list of
        per-item result dicts with keys:

        * ``key`` – the test config key
        * ``label`` – the human-readable label
        * ``points`` – max points available
        * ``points_awarded`` – points actually earned (0 or *points*)
        * ``passed`` – boolean
        * ``extra_credit`` – whether this item is extra credit
        * ``marker`` – the ``ag_*`` marker string
        * ``test_results`` – list of per-pytest-function result dicts
    """
    # Build a lookup: marker -> list of PytestTestResult.
    marker_index: dict[str, list[PytestTestResult]] = {}
    for test in run_result.tests:
        for marker in test.markers:
            marker_index.setdefault(marker, []).append(test)

    total_score = 0
    details: list[dict] = []

    for config in test_configs:
        marker = pytest_marker_for_key(config.key)
        matching_tests = marker_index.get(marker, [])

        # Item passes only when ALL matching tests passed and at least one
        # matching test exists.
        passed = len(matching_tests) > 0 and all(
            t.outcome == "passed" for t in matching_tests
        )
        points_awarded = config.points if passed else 0
        total_score += points_awarded

        test_result_details = [
            {
                "nodeid": t.nodeid,
                "outcome": t.outcome,
                "duration": t.duration,
                "message": t.message,
                "actual": t.actual,
                "expected": t.expected,
            }
            for t in matching_tests
        ]

        details.append(
            {
                "key": config.key,
                "label": config.label,
                "points": config.points,
                "points_awarded": points_awarded,
                "passed": passed,
                "extra_credit": config.extra_credit,
                "marker": marker,
                "test_results": test_result_details,
            }
        )

    return total_score, details
